create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

-- Preserve users that existed before this migration was applied.
insert into public.profiles (id, email)
select id, email from auth.users
on conflict (id) do update set email = excluded.email;

create table if not exists public.stores (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 120),
  slug text not null check (
    slug = lower(slug)
    and slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
    and char_length(slug) between 3 and 64
  ),
  logo_path text,
  brand_color text check (brand_color is null or brand_color ~ '^#[0-9a-fA-F]{6}$'),
  pickup_instructions text check (pickup_instructions is null or char_length(pickup_instructions) <= 1000),
  is_public boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (slug)
);

create table if not exists public.items (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  category text check (category is null or category in (
    'shirt', 'blouse', 'top', 'sweater', 'hoodie', 'cardigan',
    'coat', 'jacket', 'dress', 'jumpsuit', 'pants', 'trousers', 'skirt'
  )),
  youcam_category text check (youcam_category is null or youcam_category in ('upper_body', 'full_body', 'lower_body')),
  size text check (size is null or char_length(trim(size)) between 1 and 40),
  brand text check (brand is null or char_length(trim(brand)) between 1 and 100),
  condition text check (condition is null or char_length(trim(condition)) between 1 and 80),
  price numeric(12,2) check (price is null or (price > 0 and price <= 1000000)),
  currency char(3) default 'USD' check (currency is null or currency ~ '^[A-Z]{3}$'),
  notes text check (notes is null or char_length(notes) <= 2000),
  status public.item_status not null default 'draft',
  -- Generated by the trusted create-draft route. Null is allowed for older
  -- clients, while the unique constraint makes retries idempotent when a
  -- request token is supplied.
  client_request_token uuid unique,
  reserved_until timestamptz,
  published_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  -- Draft/processing records may be incomplete while YouCam runs. A seller
  -- can publish only after all required fields are present; catalog image
  -- readiness is checked by the trusted publish route.
  check (
    status in ('draft', 'processing', 'archived')
    or (
      status in ('available', 'reserved', 'sold')
      and category is not null
      and youcam_category is not null
      and size is not null
      and brand is not null
      and condition is not null
      and price is not null
      and currency is not null
      and published_at is not null
    )
  )
);

create table if not exists public.item_images (
  id uuid primary key default gen_random_uuid(),
  item_id uuid not null references public.items(id) on delete cascade,
  kind public.item_image_kind not null,
  storage_path text not null check (
    char_length(storage_path) between 1 and 1000
    and storage_path not like '%..%'
  ),
  mime_type text not null check (mime_type in ('image/jpeg', 'image/png')),
  width integer not null check (width > 0 and width <= 4096),
  height integer not null check (height > 0 and height <= 4096),
  bytes bigint not null check (bytes > 0 and bytes <= 10485760),
  is_public boolean not null default false,
  created_at timestamptz not null default timezone('utc', now()),
  unique (item_id, kind),
  check (is_public = (kind = 'catalog'))
);

create table if not exists public.try_on_sessions (
  id uuid primary key default gen_random_uuid(),
  item_id uuid not null references public.items(id) on delete cascade,
  store_id uuid not null references public.stores(id) on delete cascade,
  source_storage_path text check (source_storage_path is null or (char_length(source_storage_path) between 1 and 1000 and source_storage_path not like '%..%')),
  result_storage_path text check (result_storage_path is null or (char_length(result_storage_path) between 1 and 1000 and result_storage_path not like '%..%')),
  youcam_task_id text,
  status public.try_on_status not null default 'pending',
  error_code text,
  error_message text check (error_message is null or char_length(error_message) <= 1000),
  expires_at timestamptz not null default (timezone('utc', now()) + interval '30 minutes'),
  created_at timestamptz not null default timezone('utc', now()),
  completed_at timestamptz
);

create table if not exists public.processing_jobs (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  item_id uuid references public.items(id) on delete cascade,
  try_on_session_id uuid references public.try_on_sessions(id) on delete cascade,
  operation public.processing_operation not null,
  youcam_task_id text,
  status public.processing_status not null default 'pending',
  attempt_count integer not null default 0 check (attempt_count >= 0),
  error_code text,
  error_message text check (error_message is null or char_length(error_message) <= 1000),
  created_at timestamptz not null default timezone('utc', now()),
  completed_at timestamptz,
  check (
    (operation = 'background_removal' and item_id is not null and try_on_session_id is null)
    or (operation = 'try_on' and try_on_session_id is not null)
  )
);

create table if not exists public.reservations (
  id uuid primary key default gen_random_uuid(),
  item_id uuid not null references public.items(id) on delete cascade,
  store_id uuid not null references public.stores(id) on delete cascade,
  request_token uuid not null default gen_random_uuid(),
  buyer_name text not null check (char_length(trim(buyer_name)) between 1 and 120),
  buyer_contact text not null check (char_length(trim(buyer_contact)) between 1 and 200),
  notes text check (notes is null or char_length(notes) <= 500),
  status public.reservation_status not null default 'active',
  reserved_until timestamptz not null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (request_token)
);

