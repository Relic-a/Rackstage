-- Expiration is deliberately a simple database function. Call it before
-- storefront reads and reservations (or schedule it with Supabase Cron) so a
-- reservation can never block a one-of-one item after its deadline.
create or replace function public.release_expired_reservations()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  released integer := 0;
begin
  update public.reservations
  set status = 'expired', updated_at = timezone('utc', now())
  where status = 'active' and reserved_until <= timezone('utc', now());

  update public.items i
  set status = 'available', reserved_until = null, updated_at = timezone('utc', now())
  where i.status = 'reserved'
    and i.reserved_until is not null
    and i.reserved_until <= timezone('utc', now())
    and not exists (
      select 1 from public.reservations r
      where r.item_id = i.id and r.status = 'active'
        and r.reserved_until > timezone('utc', now())
    );
  get diagnostics released = row_count;
  return released;
end;
$$;

-- Mark expired shopper sessions and return the private paths that a trusted
-- server must delete through the Supabase Storage API. Do not delete directly
-- from storage.objects: SQL metadata deletion can leave the underlying object
-- behind. Once the server has deleted the paths, it should clear them and may
-- remove the expired session row. Keep this function small enough to call
-- opportunistically from a trusted route or schedule with Supabase Cron.
drop function if exists public.cleanup_expired_try_ons();
create function public.cleanup_expired_try_ons()
returns table (
  session_id uuid,
  source_storage_path text,
  result_storage_path text
)
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.try_on_sessions
  set status = 'expired', completed_at = coalesce(completed_at, timezone('utc', now()))
  where expires_at <= timezone('utc', now()) and status <> 'expired';

  -- Rows whose paths are already null were physically cleaned by the server;
  -- remove those old markers after one additional day. Rows with paths remain
  -- so a later cleanup call can return them again if a delete was interrupted.
  delete from public.try_on_sessions
  where status = 'expired'
    and source_storage_path is null
    and result_storage_path is null
    and expires_at <= timezone('utc', now()) - interval '1 day';
  return query
  select s.id, s.source_storage_path, s.result_storage_path
  from public.try_on_sessions s
  where s.status = 'expired'
    and s.expires_at <= timezone('utc', now())
    and (s.source_storage_path is not null or s.result_storage_path is not null)
  order by s.expires_at asc;
end;
$$;

create or replace function public.reserve_item(
  p_item_id uuid,
  p_reserved_until timestamptz,
  p_buyer_name text,
  p_buyer_contact text,
  p_notes text default null,
  p_request_token uuid default gen_random_uuid()
)
returns public.reservations
language plpgsql
security definer
set search_path = public
as $$
declare
  existing public.reservations;
  inserted public.reservations;
  item_store_id uuid;
begin
  perform public.release_expired_reservations();

  if p_reserved_until <= timezone('utc', now())
    or p_reserved_until > timezone('utc', now()) + interval '48 hours' then
    raise exception using errcode = '22023', message = 'invalid_reservation_window';
  end if;
  if char_length(trim(coalesce(p_buyer_name, ''))) = 0
    or char_length(trim(coalesce(p_buyer_contact, ''))) = 0 then
    raise exception using errcode = '22023', message = 'buyer_details_required';
  end if;

  select * into existing from public.reservations where request_token = p_request_token;
  if found then return existing; end if;

  update public.items
  set status = 'reserved', reserved_until = p_reserved_until,
      updated_at = timezone('utc', now())
  where id = p_item_id and status = 'available'
  returning store_id into item_store_id;

  if item_store_id is null then
    -- A concurrent idempotent request may have committed while this request
    -- waited for the item row lock. Return it instead of creating a duplicate.
    select * into existing from public.reservations where request_token = p_request_token;
    if found then return existing; end if;
    raise exception using errcode = 'P0001', message = 'item_unavailable';
  end if;

  insert into public.reservations (
    item_id, store_id, request_token, buyer_name, buyer_contact, notes,
    status, reserved_until
  ) values (
    p_item_id, item_store_id, p_request_token, trim(p_buyer_name),
    trim(p_buyer_contact), nullif(trim(p_notes), ''), 'active', p_reserved_until
  )
  on conflict (request_token) do nothing
  returning * into inserted;

  if inserted.id is null then
    select * into existing from public.reservations where request_token = p_request_token;
    if found then return existing; end if;
    raise exception using errcode = 'P0001', message = 'reservation_failed';
  end if;
  return inserted;
end;
$$;

-- Supabase service_role is the only role allowed to run these server-side
-- operations. No anonymous database write can bypass this boundary.
