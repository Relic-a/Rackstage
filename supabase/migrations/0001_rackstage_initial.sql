-- New email/magic-link users receive a profile row. The function is
-- intentionally security-definer because auth.users is not client-readable.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, display_name)
  values (new.id, new.email, coalesce(new.raw_user_meta_data ->> 'name', new.raw_user_meta_data ->> 'full_name'))
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.is_store_owner(p_store_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.stores
    where id = p_store_id and owner_id = auth.uid()
  );
$$;

create or replace function public.is_item_owner(p_item_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.items i
    join public.stores s on s.id = i.store_id
    where i.id = p_item_id and s.owner_id = auth.uid()
  );
$$;

create or replace function public.storage_path_is_owned(p_path text)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  store_id uuid;
begin
  begin
    store_id := split_part(p_path, '/', 1)::uuid;
  exception when invalid_text_representation then
    return false;
  end;
  return public.is_store_owner(store_id);
end;
$$;

