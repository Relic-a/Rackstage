-- RackStage MVP schema.
-- Apply with `supabase db push` or the Supabase SQL editor.
-- Secret-key operations (YouCam, private uploads, reservation RPC) stay in
-- trusted server routes. Anonymous clients receive only published storefront
-- rows through the RLS policies below.

